import java.util.Properties

// Optional local release signing. keystore.properties (git-ignored, next to settings.gradle.kts):
//   storeFile=C:/path/to/keystore   storePassword=...   keyAlias=...   keyPassword=...
// Without it, release outputs stay unsigned and scripts/build.ps1 can sign them from env vars.
val keystoreProperties = rootProject.file("keystore.properties").takeIf { it.exists() }?.let { file ->
    Properties().apply { file.inputStream().use { load(it) } }
}

plugins {
    alias(libs.plugins.android.application)
    alias(libs.plugins.kotlin.compose)
    alias(libs.plugins.kotlin.serialization)
}

android {
    namespace = "com.neuralnexusstudios.nex_remote"
    // compileSdk 37 is required by Compose 1.12 / com.composables:ui. targetSdk stays 36.
    compileSdk {
        version = release(37)
    }

    defaultConfig {
        applicationId = "com.neuralnexusstudios.nex_remote"
        minSdk = 26
        targetSdk = 36
        versionCode = 5
        versionName = "1.3.0"
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        vectorDrawables.useSupportLibrary = true
    }

    signingConfigs {
        if (keystoreProperties != null) {
            create("release") {
                storeFile = file(keystoreProperties.getProperty("storeFile"))
                storePassword = keystoreProperties.getProperty("storePassword")
                keyAlias = keystoreProperties.getProperty("keyAlias")
                keyPassword = keystoreProperties.getProperty("keyPassword") ?: keystoreProperties.getProperty("storePassword")
            }
        }
    }

    buildTypes {
        debug {
            applicationIdSuffix = ".debug"
            versionNameSuffix = "-debug"
        }
        release {
            signingConfig = signingConfigs.findByName("release")
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(
                getDefaultProguardFile("proguard-android-optimize.txt"),
                "proguard-rules.pro",
            )
        }
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    packaging {
        resources {
            excludes += "/META-INF/{AL2.0,LGPL2.1}"
        }
    }

    androidResources {
        // The app's own UI strings are English-only; this only trims translated
        // string tables that AndroidX/Material/Play Services ship for their internal
        // (mostly accessibility) strings, not app content.
        localeFilters += "en"
    }
}

